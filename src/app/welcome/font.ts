export const GLYPH_SIZE = 8;

const GLYPHS = HEX.map((hex) => Array.from({ length: GLYPH_SIZE }, (_, i) => parseInt(hex.slice(i * 2, i * 2 + 2), 16)));

/** The eight row bitmaps for `ch` (anything outside printable ASCII draws as "?"). */
export function glyph(ch: string): readonly number[] {
  const code = ch.charCodeAt(0);
  return GLYPHS[code >= 32 && code < 127 ? code - 32 : 31];
}
